#!/usr/bin/env python3
"""Figure 2: native attack success and utility change on paired AgentDojo keys.

Two aligned panels over the same twelve model x suite rows:
  (a) native attack success, baseline vs GrantBind (dumbbell)
  (b) paired task-success change in percentage points (diverging bars)

The data comes from paper/fig/results-tradeoff.csv, itself generated by
extract_paper_numbers.py from results/workshop/agentdojo.  Python/matplotlib is
the selected nature-figure backend (no R on this machine).
"""
from __future__ import annotations

import csv
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import matplotlib as mpl
import numpy as np
from matplotlib.gridspec import GridSpec

HERE = Path(__file__).resolve().parent
SKILL_SCRIPTS = Path("/Users/luo/.cc-switch/skills/nature-figure/scripts")
sys.path.insert(0, str(SKILL_SCRIPTS))
from audit_panel_alignment import require_matplotlib_panel_alignment  # noqa: E402

CSV_PATH = HERE / "results-tradeoff.csv"
STEM = HERE / "results-tradeoff"

BASE = "#7a8699"
DEFENDED = "#1f5c7a"
NEG = "#a63d2f"
RULE = "#c9d0d8"
GRID = "#e6eaee"
INK = "#1d2b36"
MUTED = "#5f7183"

MODEL_LABEL = {"qwen": "Qwen3.7", "deepseek": "DeepSeek", "qwen38": "Qwen3.8"}
SUITES = ("workspace", "travel", "banking", "slack")
ROWS = [(model, suite) for model in MODEL_LABEL for suite in SUITES]
# Leave one blank row between model groups.
Y = {key: 12 - row - row // len(SUITES) for row, key in enumerate(ROWS)}


def read_rows() -> dict[tuple[str, str], dict]:
    data = {}
    with CSV_PATH.open(newline="", encoding="utf-8") as handle:
        for row in csv.DictReader(handle):
            key = (row["model"], row["suite"])
            data[key] = {
                "n": int(row["n"]),
                "base_tsr": float(row["base_tsr"]),
                "dscg_tsr": float(row["dscg_tsr"]),
                "base_asr": float(row["base_asr"]),
                "dscg_asr": float(row["dscg_asr"]),
                "delta": float(row["delta_tsr_pp"]),
            }
    return data


def main() -> int:
    mpl.rcParams.update(
        {
            "font.family": "sans-serif",
            "font.sans-serif": ["Arial", "Helvetica", "DejaVu Sans"],
            "font.size": 7,
            "axes.linewidth": 0.7,
            "axes.spines.right": False,
            "axes.spines.top": False,
            "axes.edgecolor": MUTED,
            "axes.labelcolor": INK,
            "xtick.color": MUTED,
            "ytick.color": INK,
            "xtick.labelsize": 6.3,
            "ytick.labelsize": 6.4,
            "xtick.major.width": 0.7,
            "ytick.major.width": 0.7,
            "xtick.major.size": 2.4,
            "ytick.major.size": 0,
            "axes.unicode_minus": False,
            "pdf.fonttype": 42,
            "svg.fonttype": "none",
            "savefig.dpi": 600,
        }
    )

    data = read_rows()
    fig = plt.figure(figsize=(7.16, 3.25))
    gs = GridSpec(1, 2, figure=fig, width_ratios=(1, 1), wspace=0.10)
    ax_a = fig.add_subplot(gs[0, 0])
    ax_b = fig.add_subplot(gs[0, 1], sharey=ax_a)
    fig.subplots_adjust(left=0.255, right=0.985, top=0.86, bottom=0.19)

    for key in ROWS:
        y = Y[key]
        row = data[key]
        # (a) dumbbell: baseline hollow circle above, DEFENDED filled square below.
        ax_a.plot(
            [row["base_asr"], row["dscg_asr"]],
            [y + 0.20, y - 0.20],
            color=RULE,
            lw=1.0,
            solid_capstyle="round",
            zorder=1,
        )
        ax_a.scatter(
            row["base_asr"],
            y + 0.20,
            s=19,
            facecolors="white",
            edgecolors=BASE,
            linewidths=0.9,
            zorder=3,
        )
        ax_a.scatter(
            row["dscg_asr"],
            y - 0.20,
            s=15,
            marker="s",
            facecolors=DEFENDED,
            edgecolors=DEFENDED,
            linewidths=0.8,
            zorder=3,
        )
        # (b) paired task-success change.
        delta = row["delta"]
        color = DEFENDED if delta >= 0 else NEG
        ax_b.barh(y, delta, height=0.56, color=color, alpha=0.86, linewidth=0)
        ax_b.text(
            delta + (1.2 if delta >= 0 else -1.2),
            y,
            f"{delta:+.1f}" if delta else "0.0",
            ha="left" if delta >= 0 else "right",
            va="center",
            fontsize=6.0,
            color=color,
        )

    # Shared styling -----------------------------------------------------
    labels = [f"{MODEL_LABEL[m]} \u00b7 {s.title()} (n={data[(m, s)]['n']})" for m, s in ROWS]
    ax_a.set_yticks([Y[k] for k in ROWS])
    ax_a.set_yticklabels(labels)
    ax_a.set_ylim(-1.7, 12.7)
    ax_a.set_xlim(-4, 64)
    ax_a.set_xticks([0, 20, 40, 60])
    ax_a.set_xlabel("Native ASR (%)", labelpad=4)

    ax_b.set_xlim(-18, 30)
    ax_b.set_xticks([-10, 0, 10, 20, 30])
    ax_b.set_xlabel("Task-success change (pp)", labelpad=4)
    ax_b.axvline(0, color=MUTED, lw=0.8, zorder=2)
    ax_b.set_axisbelow(True)
    ax_b.tick_params(axis="y", left=False, labelleft=False)

    for ax in (ax_a, ax_b):
        ax.axhline(3.0, color=GRID, lw=0.8, ls=(0, (2, 3)), zorder=0)
        ax.axhline(8.0, color=GRID, lw=0.8, ls=(0, (2, 3)), zorder=0)
        ax.tick_params(axis="x", pad=2)

    ax_a.text(
        0.0,
        1.055,
        "(a) Native attack success",
        transform=ax_a.transAxes,
        ha="left",
        va="bottom",
        fontsize=7.3,
        fontweight="bold",
        color=INK,
    )
    ax_b.text(
        0.0,
        1.055,
        "(b) Task-success change",
        transform=ax_b.transAxes,
        ha="left",
        va="bottom",
        fontsize=7.3,
        fontweight="bold",
        color=INK,
    )

    # Legend: hollow = baseline, filled = DEFENDED.
    from matplotlib.lines import Line2D

    handles = [
        Line2D(
            [0],
            [0],
            marker="o",
            linestyle="none",
            markerfacecolor="white",
            markeredgecolor=BASE,
            markeredgewidth=0.9,
            markersize=4.2,
            label="Baseline",
        ),
        Line2D(
            [0],
            [0],
            marker="s",
            linestyle="none",
            markerfacecolor=DEFENDED,
            markeredgecolor=DEFENDED,
            markersize=3.8,
            label="GrantBind",
        ),
    ]
    ax_a.legend(
        handles=handles,
        loc="lower right",
        bbox_to_anchor=(1.0, -0.02),
        fontsize=6.2,
        frameon=False,
        handletextpad=0.5,
        borderaxespad=0.2,
        ncol=1,
    )

    # Hard gate: equal panel widths and shared row geometry.
    require_matplotlib_panel_alignment(
        fig,
        json_out=f"{STEM}.alignment.json",
        overlay_svg=f"{STEM}.alignment.svg",
        tolerance_pt=1.5,
        gutter_tolerance_pt=1.5,
        strict=True,
    )

    fig.savefig(f"{STEM}.pdf", bbox_inches="tight", pad_inches=0.02)
    svg = STEM.with_suffix(".svg")
    fig.savefig(svg, bbox_inches="tight", pad_inches=0.02)
    # Matplotlib adds trailing spaces to wrapped SVG path coordinates.
    svg.write_text("\n".join(line.rstrip() for line in svg.read_text(encoding="utf-8").splitlines()) + "\n",
                   encoding="utf-8")
    fig.savefig(f"{STEM}.png", dpi=600, bbox_inches="tight", pad_inches=0.02)
    print(f"wrote {STEM}.pdf/.svg/.png")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
